## 并发与并行的区别：
# 并发 指多个任务在同一个cpu内核中通过 通过切片时间交替执行任务
# 并行 指多个任务在多个cpu内核中同一时间执行

## 进程与线程的关系：
# 一个应用程序可以有多个进程，默认至少一个主进程，可以创建多个子进程
# 一个进程中至少默认一个主线程，可以创建多个子线程

## 进程与线程区别：
# 进程为系统中资源分配最小单元，线程为系统中算力调配最小单位
# 进程之间数据不共享，同一进程中多个线程之间数据可以进行互相访问
# 每启动一个进程需要独立分配资源与拷贝访问数据，所以进程的启动与销毁代价比较大
# 一个进程中可以并发多个线程 单cpu内核即可

# 简而言之：
# 线程：cpu调度最小单位
# 进程：资源分配的最小单位
