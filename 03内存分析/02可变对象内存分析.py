# 不可变对象：object()、list[]、dict{}、set{}
# 可变不可变是指：指的是改变值后，内存地址是否发生改变
lis: list = [1, 2, 3]
lis[1] = 10
# lis 会存放在栈中内存xxx
# list会存放在堆中开辟内存id:9999，type:list, value存放了0:123、1:456、2:789， 1、2、3会存放在堆中 id:123、456、789
# 修改lis下标1=10，此时：栈中内存不变xxx、堆中内存不变9999,value会变成：0:123、1:8899、2:789 ，10会存放在堆中 id:8899
# 值会修改value 1下标指向的内存地址，由原来789->8899,此时 789内存会被释放
# 所以lis 对象不可变
