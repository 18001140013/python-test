# 不可变对象：1、元组tuple 2、基本类型：str、int、float、bool
# 可变不可变指的是存放在堆中的内存，如果值发生变化，就会新建对象到堆中
# 可变不可变是指：指的是改变值后，内存地址是否发生改变
# 所有变量名存放在栈中，所有指向值都会存放在堆中，不可变对象在堆中会以value形式再次存放其他对象的内存值，所以自生内存不会发生变化
# 例如list[a,b,c]，堆中有list、a、b、c; 然而list.value=0:a、1:b、2:c
str = '丽丽'
str2 = str
str = '丽丽2'
str2 = str
# str、ste2 这2名字会存在栈中
# 丽丽这个值会存在堆中，id=1234
# str、str2 指向的内存地址都是堆中1234
# 如果此时的丽丽 改为 丽丽1 ， 就会在堆中新开辟一块地址存放 12345
# 赋值给str、str2 在栈中没有变化，但指向的内存地址变成了 12345
